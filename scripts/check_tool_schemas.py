"""Prove the StructuredTool schemas still match the contract the model was tuned on.

The eight tool schemas are generated by LangChain from the Pydantic models in
patient_tools.py, so one object defines both what the model may call and what
actually runs and the two cannot drift apart.

That makes the schema the model sees a *derived* artefact. Every description
steers routing -- `check_behaviour.py` asserts which tool the model picks for 27
questions -- so an edit that alters a description, drops a parameter, or changes a
required list changes routing, and the failure surfaces only in a live test that
costs minutes and an endpoint to run.

So the emitted schemas are compared here against a snapshot of the intended
contract, offline and in under a second.

Strict about anything that steers the model: parameter names, JSON types, required
lists, and any description the snapshot specifies. Permissive about additions --
`default` keys that Pydantic emits, and descriptions on parameters the snapshot
leaves undescribed -- but it prints them, because "permissive" should not mean
"invisible".

    python3 scripts/check_tool_schemas.py [--verbose]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "databricks"))

from patient_tools import build_patient_tools, model_facing_specs  # noqa: E402
from record_tools import PatientRecordTools  # noqa: E402

EXPECTED_FILE = ROOT / "scripts" / "tool_schemas_expected.json"


def generated_schemas() -> dict[str, dict]:
    """The schemas LangChain will send to the model, keyed by tool name.

    No executor and no config: nothing here runs a query, it only reads the
    declared signatures, so the check needs no workspace and no credentials.
    """
    record_tools = PatientRecordTools(
        executor=None,  # type: ignore[arg-type]
        documents_table="workspace.default.patient_history_documents",
        config={},
    )
    tools = build_patient_tools(record_tools, {})
    return {spec["function"]["name"]: spec for spec in model_facing_specs(tools)}


def compare(expected: dict, actual: dict) -> tuple[list[str], list[str]]:
    """Return (breaking differences, benign additions) for one tool."""
    breaks: list[str] = []
    notes: list[str] = []
    name = expected["name"]

    if actual.get("description") != expected.get("description"):
        breaks.append(
            f"{name}: tool description changed\n"
            f"      was: {expected.get('description')!r}\n"
            f"      now: {actual.get('description')!r}"
        )

    want = expected.get("parameters", {}).get("properties", {})
    got = actual.get("parameters", {}).get("properties", {})

    for missing in sorted(set(want) - set(got)):
        breaks.append(f"{name}.{missing}: parameter disappeared")
    for added in sorted(set(got) - set(want)):
        # patient_id appearing here means the injection guard broke and the model
        # can choose the patient -- the one thing that must never drift.
        severity = breaks if added == "patient_id" else notes
        severity.append(f"{name}.{added}: parameter added")

    for key in sorted(set(want) & set(got)):
        wanted, given = want[key], got[key]
        if wanted.get("type") != given.get("type"):
            breaks.append(
                f"{name}.{key}: type {wanted.get('type')!r} -> {given.get('type')!r}"
            )
        if "description" in wanted:
            if wanted["description"] != given.get("description"):
                breaks.append(
                    f"{name}.{key}: description changed\n"
                    f"      was: {wanted['description']!r}\n"
                    f"      now: {given.get('description')!r}"
                )
        elif given.get("description"):
            notes.append(f"{name}.{key}: description added")
        if "default" in given and "default" not in wanted:
            notes.append(f"{name}.{key}: default {given['default']!r} added")

    if sorted(expected.get("parameters", {}).get("required", []) or []) != sorted(
        actual.get("parameters", {}).get("required", []) or []
    ):
        breaks.append(
            f"{name}: required list changed "
            f"{expected.get('parameters', {}).get('required')} -> "
            f"{actual.get('parameters', {}).get('required')}"
        )
    return breaks, notes


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verbose", action="store_true", help="print each schema")
    args = parser.parse_args()

    expected = {
        spec["function"]["name"]: spec["function"]
        for spec in json.loads(EXPECTED_FILE.read_text())
    }
    actual = {name: spec["function"] for name, spec in generated_schemas().items()}

    breaks: list[str] = []
    notes: list[str] = []

    for gone in sorted(set(expected) - set(actual)):
        breaks.append(f"{gone}: tool no longer offered to the model")
    for new in sorted(set(actual) - set(expected)):
        breaks.append(f"{new}: tool offered that the snapshot does not know")

    for name in sorted(set(expected) & set(actual)):
        tool_breaks, tool_notes = compare(expected[name], actual[name])
        breaks += tool_breaks
        notes += tool_notes
        if args.verbose:
            print(f"\n--- {name} ---")
            print(json.dumps(actual[name], indent=2, sort_keys=True))

    print(f"\n  {len(expected)} tools in snapshot, {len(actual)} generated")
    if notes:
        print(f"\n  {len(notes)} benign addition(s):")
        for note in notes:
            print(f"    + {note}")
    if breaks:
        print(f"\n  {len(breaks)} BREAKING difference(s):")
        for issue in breaks:
            print(f"    ! {issue}")
        print("\n  FAIL - the model would be offered a different contract.")
        return 1
    print("\n  ok - the model is offered the same contract as before.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
